"""Give g j p q y a real tail, now that the box has two rows under the baseline.

The bowl of the g opens to six rows so the hook below it keeps the full stroke;
p and q only lengthen the stem they already had. Nothing else moves.
"""

from pixelfont import GLYPHS, read_maps, write_maps

SHAPES = {
    "regular": {
        "g": [".########..", "##########.", "##......##.", "##......##.", "##......##.",
              "##########.", ".#########.", "........##.", ".#########.", ".#######..."],
        "y": ["##......##.", "##......##.", "##......##.", "##......##.", "##......##.",
              "##########.", ".#########.", "........##.", ".#########.", ".#######..."],
        "p": [".########..", "##########.", "##......##.", "##......##.", "##########.",
              "#########..", "##.........", "##.........", "##.........", "##........."],
        "q": [".########..", "##########.", "##......##.", "##......##.", "##########.",
              ".#########.", "........##.", "........##.", "........##.", "........##."],
        "j": ["........##.", "........##.", "........##.", "........##.", "........##.",
              "........##.", "........##.", ".#########.", ".#######..."],
    },
    "thin": {
        "g": [".########..", "#........#.", "#........#.", "#........#.", "#........#.",
              ".#########.", ".........#.", ".........#.", ".........#.", ".########.."],
        "y": ["#........#.", "#........#.", "#........#.", "#........#.", "#........#.",
              ".#########.", ".........#.", ".........#.", ".........#.", ".########.."],
        "p": [".########..", "#........#.", "#........#.", "#........#.", "#########..",
              "#..........", "#..........", "#..........", "#..........", "#.........."],
        "q": [".########..", "#........#.", "#........#.", "#........#.", ".#########.",
              ".........#.", ".........#.", ".........#.", ".........#.", ".........#."],
        "j": [".........#.", ".........#.", ".........#.", ".........#.", ".........#.",
              ".........#.", ".........#.", ".........#.", ".########.."],
    },
}

# Where the drawn part starts, counted from the top of the box (y = 11).
FIRST_ROW = {"g": 4, "y": 4, "p": 4, "q": 4, "j": 5}
BLANK = "." * 11


def main():
    for weight, shapes in SHAPES.items():
        path = GLYPHS / f"{weight}.txt"
        maps = read_maps(path)
        for name, body in shapes.items():
            cp, old = maps[name]
            rows = list(old[:FIRST_ROW[name]]) + list(body)
            rows += [BLANK] * (len(old) - len(rows))
            assert len(rows) == len(old), (name, len(rows))
            maps[name] = (cp, rows)
        header = path.read_text(encoding="utf-8").split("\n@")[0]
        write_maps(path, maps, header)
        print(f"{path.name}: {len(shapes)} descendantes")


if __name__ == "__main__":
    main()
