def pad(first, rows):
    out = [BLANK] * first + [r.ljust(CELL_W, ".") for r in rows]
    return out + [BLANK] * (ROWS - len(out))


def main():
    for weight in ("regular", "thin"):
        path = GLYPHS / f"{weight}.txt"
        maps = read_maps(path)
        entries = dict(SHARED, **STROKED[weight])
        for name, (cp, first, rows) in entries.items():
            maps[name] = (cp, pad(first, rows))
        header = path.read_text(encoding="utf-8").split("\n@")[0]
        write_maps(path, maps, header)
        print(f"{path.name}: {len(entries)} meubles, {len(maps)} glyphes en tout")


if __name__ == "__main__":
    main()
