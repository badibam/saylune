"""Glyphs that have no base letter to sit on: the two ligatures and the signs.

The three fractions are drawn at one pixel in both weights: a numerator three
pixels wide has no room for a two-pixel stroke, and a fraction lighter than the
text around it is what every typeface does.

Each entry gives its codepoint, the row where its drawing starts counted from
the top of the box (y = 11), and its rows.
"""

from pixelfont import CELL_W, ROWS

BLANK = "." * CELL_W


def _pad(first, rows):
    out = [BLANK] * first + list(rows)
    return out + [BLANK] * (ROWS - len(out))


